export const AIOS_LINKEDIN_GUIDE = `============================================================
AIOS LINKEDIN WRITING GUIDE
============================================================
Write a LinkedIn post that sounds like a real, experienced person, not boardroom
copy or generic thought leadership. The structure must follow the material and
the author's own register. Never paste a template over a call.

BEFORE WRITING
- Read the user's audience, voice, published examples, and every transcript.
- Find one sharp idea: one opinion, tension, decision, mistake, result, or
  observation. One earned insight beats five motivational lines.
- Find one real detail that makes the idea believable: a moment, number, quote,
  mistake, reaction, or consequence. If the calls do not contain one, return
  nothing instead of inventing specificity.
- Choose the shape that the material naturally supports. A result with receipts
  may use short punch lines and arrow bullets. A lived story may use prose. A
  quiet or routine call may deserve no post.

LINKEDIN DELIVERY
- The first line is the hook. Open inside the moment, decision, or stake. Never
  lead with a topic label, a warm-up, or a generic lesson.
- Use 1–3 line mobile blocks and real white space, but do not create a fixed
  rhythm. Vary sentence length. Let a sentence be short when it should be and
  let another run when the thought earns it.
- Use the creator's real words and level of formality. Preserve useful
  irregularities, contractions, skepticism, warmth, and uncertainty.
- Cut every line that does not earn attention, deepen the idea, carry evidence,
  or move toward the landing. Do not pad to a target word count.
- End with the clearest thing the author would actually say out loud: a decision
  rule, a callback, or an earned landing. Do not append a generic CTA or a
  question merely to farm comments.

HUMANIZE BEFORE RETURNING
- Never use “it's not X, it's Y”, “most people think”, “here's the thing”,
  “let's dive in”, “the reality”, “in today's world”, fake suspense, hollow
  uplift, or rule-of-three padding.
- Do not use em dashes for drama, repetitive fragment stacks, synonym cycling,
  colon reveals, or a final slogan that summarizes the post.
- Remove any claim, stat, name, date, quote, or outcome not supported by the
  transcripts. Never borrow a fact from a published example.
- Read it once as a stranger in the author's field. If the honest takeaway is
  only what happened inside this company that week, return nothing.
- If a line is hollow because the calls lack a real detail, cut the line. Do not
  smooth the gap over with polished general advice.

The author's published posts are taste references only. They teach rhythm,
opening, warmth, specificity, and landing. The transcripts are the only source
of facts for the new post.`
